const SAY_RE = new RegExp(
  `(^|[^\\p{L}])(${Object.keys(SAY).sort((a, b) => b.length - a.length).join('|')})(?=[^\\p{L}]|$)`,
  'giu',
)
// Text for the voice: the words on screen, with original-language terms respelled.
// "bad" (linen) is only respelled where the page marks it as a term.
function speakable(el: HTMLElement) {
  const marked = new Set([...el.querySelectorAll('.term-inline')].map((t) => t.textContent?.toLowerCase()))
  // Initials such as "E. J. Waggoner" are read without the full stops, so the voice does not pause.
  const text = el.innerText
    .replace(/\b([A-Z])\.\s(?=[A-Z])/g, '$1 ')
    // "p. 347" and "pp. 477-478" are read as "page" and "pages".
    .replace(/\bpp\.\s(?=\d)/g, 'pages ')
    .replace(/\bp\.\s(?=\d)/g, 'page ')
    .replace(/\bch\.\s(?=\d)/g, 'chapter ')
  return text.replace(SAY_RE, (m, pre: string, word: string) => {
    const key = word.toLowerCase()
    if (key === 'bad' && !marked.has('bad')) return m
    return pre + SAY[key]
  })
}

// Split long paragraphs into sentence groups so audio starts quickly.
function chunks(text: string) {
  const sentences = text.replace(/\s+/g, ' ').match(/[^.!?]+[.!?"”')]*\s*/g) ?? [text]
  const out: string[] = []
  let cur = ''
  for (const s of sentences) {
    if ((cur + s).length > 260 && cur) {
      out.push(cur.trim())
      cur = ''
    }
    cur += s
  }
  if (cur.trim()) out.push(cur.trim())
  return out
}

export default function ReadAloud() {
  const { pathname } = useLocation()
  const reduce = useReducedMotion()
  const [open, setOpen] = useState(false)
  const [voice, setVoice] = useState<string>(() => {
    const v = store.get(VOICE_KEY)
    return VOICES.some((x) => x.id === v) ? (v as string) : VOICES[0].id
  })
  const [rate, setRate] = useState<number>(() => {
    const r = Number(store.get(RATE_KEY))
    return r >= RATE_MIN && r <= RATE_MAX ? r : 1
  })
  const [state, setState] = useState<'idle' | 'loading' | 'playing' | 'paused'>('idle')
  const [error, setError] = useState('')

  const audio = useRef<HTMLAudioElement | null>(null)
  const queue = useRef<Item[]>([])
  const index = useRef(0)
  const run = useRef(0)
  const current = useRef<HTMLElement | null>(null)
  const urls = useRef(new Map<string, Promise<string>>())
  const settings = useRef({ voice, rate })
  const paused = useRef(false)

  const getAudio = () => {
    if (!audio.current) {
      audio.current = new Audio()
      audio.current.preload = 'auto'
      ;(window as unknown as { __readAloud?: HTMLAudioElement }).__readAloud = audio.current
    }
    return audio.current
  }

  const mark = useCallback(
    (el: HTMLElement | null) => {
      current.current?.classList.remove('reading-now')
      current.current = el
      if (el) {
        el.classList.add('reading-now')
        el.scrollIntoView({ block: 'center', behavior: reduce ? 'auto' : 'smooth' })
      }
    },
    [reduce],
  )

  const fetchUrl = (i: number): Promise<string> | null => {
    const item = queue.current[i]
    if (!item) return null
    const { voice: v, rate: r } = settings.current
    const key = `${v}|${r}|${i}`
    let p = urls.current.get(key)
    if (!p) {
      p = fetch('/api/tts', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ text: item.text, voice: v, rate: r }),
      }).then(async (res) => {
        if (!res.ok) throw new Error((await res.json().catch(() => ({}))).error || 'The voice service did not respond.')
        return URL.createObjectURL(await res.blob())
      })
      p.catch(() => urls.current.delete(key))
      urls.current.set(key, p)
    }
    return p
  }

  // Prepare the rest of the page in order, two parts at a time, so the next part is ready in time.
  const inFlight = useRef(0)
  const nextToFetch = useRef(0)
  const prefetch = (from: number) => {
    if (from > nextToFetch.current) nextToFetch.current = from
    const pump = () => {
      while (inFlight.current < 2 && nextToFetch.current < queue.current.length) {
        const j = nextToFetch.current++
        const p = fetchUrl(j)
        if (!p) continue
        inFlight.current++
        p.catch(() => {}).finally(() => {
          inFlight.current--
          pump()
        })
      }
    }
    pump()
  }

  const clearUrls = () => {
    urls.current.forEach((p) => p.then((u) => URL.revokeObjectURL(u)).catch(() => {}))
    urls.current.clear()
  }

  const playFrom = async (i: number, id: number) => {
    if (id !== run.current) return
    if (i >= queue.current.length) {
      mark(null)
      index.current = 0
      setState('idle')
      return
    }
    index.current = i
    const item = queue.current[i]
    if (current.current !== item.el) mark(item.el)
    setState((s) => (s === 'playing' ? s : 'loading'))
    try {
      const url = await fetchUrl(i)!.catch(() => fetchUrl(i)!)
      if (id !== run.current) return
      prefetch(i + 1)
      const a = getAudio()
      a.src = url
      a.onended = () => playFrom(i + 1, id)
      if (paused.current) return // paused while this part was loading
      await a.play()
      if (id === run.current) setState('playing')
    } catch (e) {
      if (id !== run.current) return
      setError(e instanceof Error ? e.message : 'The voice service did not respond.')
      setState('paused')
    }
  }

  const stop = useCallback(() => {
    run.current++
    const a = audio.current
    if (a) {
      a.pause()
      a.onended = null
      a.removeAttribute('src')
      a.load()
    }
    mark(null)
    paused.current = false
    nextToFetch.current = 0
    index.current = 0
    queue.current = []
    queuePath.current = ''
    clearUrls()
    setState('idle')
    setError('')
  }, [mark])

  // Stop when the page changes.
  useEffect(() => stop, [pathname, stop])

  const queuePath = useRef('')
  const buildQueue = () => {
    queuePath.current = pathname
    queue.current = []
    collectBlocks().forEach((el) => chunks(speakable(el)).forEach((text) => queue.current.push({ el, text })))
    nextToFetch.current = 0
    prepare(0)
  }

  // Ask the server to start preparing the page (from a given part onward) in the current voice and speed.
  const prepare = (from: number) => {
    if (!queue.current.length) return
    const { voice: v, rate: r } = settings.current
    fetch('/api/tts/prepare', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ texts: queue.current.slice(from).map((q) => q.text), voice: v, rate: r }),
    }).catch(() => {})
  }

  // Start preparing as soon as the Listen panel is opened.
  useEffect(() => {
    if (!open || state !== 'idle') return
    // Wait for the page's text to finish appearing before reading it.
    const t = window.setTimeout(() => {
      if (queuePath.current === pathname && queue.current.length) return
      clearUrls()
      buildQueue()
      prefetch(0)
    }, 800)
    return () => window.clearTimeout(t)
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [open, pathname, state])

  const play = () => {
    setError('')
    paused.current = false
    const a = getAudio()
    // Resume exactly where it paused.
    if (state === 'paused' && queue.current.length) {
      if (a.src && !a.ended && a.currentTime > 0) {
        a.play()
          .then(() => setState('playing'))
          .catch(() => playFrom(index.current, run.current))
      } else {
        playFrom(index.current, run.current)
      }
      return
    }
    const id = ++run.current
    if (!queue.current.length || queuePath.current !== pathname) {
      clearUrls()
      buildQueue()
    }
    prefetch(0)
    // Give it a head start: wait until the opening parts are ready so the reading flows without gaps.
    setState('loading')
    const head: Promise<string>[] = []
    let chars = 0
    for (let j = 0; j < queue.current.length && (j < 4 || chars < 600); j++) {
      chars += queue.current[j].text.length
      const p = fetchUrl(j)
      if (p) head.push(p.catch(() => ''))
      if (chars >= 900) break
    }
    Promise.race([Promise.all(head), new Promise((r) => setTimeout(r, 12000))]).then(() => playFrom(0, id))
  }

  const pause = () => {
    paused.current = true
    audio.current?.pause()
    setState('paused')
  }

  // A new voice or speed takes effect from the current paragraph, keeping your place.
  const restartCurrent = () => {
    // Start preparing the rest of the page in the new voice or speed straight away.
    prepare(state === 'idle' ? 0 : index.current)
    if (state === 'idle') return
    clearUrls()
    const a = audio.current
    if (a) {
      a.pause()
      a.onended = null
      a.removeAttribute('src')
    }
    const id = ++run.current
    nextToFetch.current = index.current
    prefetch(index.current)
    if (state === 'paused') setState('paused')
    else playFrom(index.current, id)
  }

  const chooseVoice = (v: string) => {
    setVoice(v)
    store.set(VOICE_KEY, v)
    settings.current = { voice: v, rate }
    restartCurrent()
  }

  const chooseRate = (r: number) => {
    setRate(r)
    store.set(RATE_KEY, String(r))
  }
  const commitRate = () => {
    if (settings.current.rate === rate) return
    settings.current = { voice, rate }
    restartCurrent()
  }

  const busy = state === 'playing' || state === 'loading'

  return (
    <div className="ra" data-noread>
      <AnimatePresence>
        {open && (
          <motion.div
            className="ra-panel"
            initial={{ opacity: 0, y: reduce ? 0 : 8 }}
            animate={{ opacity: 1, y: 0 }}
            exit={{ opacity: 0, y: reduce ? 0 : 8 }}
            transition={{ duration: reduce ? 0 : 0.2 }}
            role="dialog"
            aria-label="Read aloud"
          >
            <div className="ra-row">
              {busy ? (
                <button className="btn" onClick={pause}>{state === 'loading' ? 'Loading…' : 'Pause'}</button>
              ) : (
                <button className="btn" onClick={play}>{state === 'paused' ? 'Resume' : 'Read this page'}</button>
              )}
              <button className="btn ghost" onClick={stop} disabled={state === 'idle'}>Stop</button>
            </div>
            <label className="ra-label" htmlFor="ra-voice">Voice</label>
            <select id="ra-voice" className="ra-select" value={voice} onChange={(e) => chooseVoice(e.target.value)}>
              {VOICES.map((v) => (
                <option key={v.id} value={v.id}>{v.label}</option>
              ))}
            </select>
            <label className="ra-label" htmlFor="ra-rate">
              Speed <span>{rate.toFixed(2)}×</span>
            </label>
            <input
              id="ra-rate"
              type="range"
              min={RATE_MIN}
              max={RATE_MAX}
              step={0.05}
              value={rate}
              onChange={(e) => chooseRate(Number(e.target.value))}
              onPointerUp={commitRate}
              onKeyUp={commitRate}
            />
            {error && <p className="ra-error" role="alert">{error}</p>}
          </motion.div>
        )}
      </AnimatePresence>
      <button className={`ra-fab${state !== 'idle' ? ' on' : ''}`} onClick={() => setOpen((o) => !o)} aria-expanded={open} aria-label="Read aloud">
        <svg viewBox="0 0 24 24" aria-hidden="true" fill="none" stroke="currentColor" strokeWidth="1.8" strokeLinecap="round" strokeLinejoin="round">
          <path d="M4 9v6h4l5 4V5L8 9H4z" />
          <path d="M16 9a4 4 0 0 1 0 6M18.5 6.5a7.5 7.5 0 0 1 0 11" />
        </svg>
        <span>{state === 'playing' ? 'Reading…' : state === 'loading' ? 'Loading…' : state === 'paused' ? 'Paused' : 'Listen'}</span>
      </button>
    </div>
  )
}
